use CodeIgniter\Database\Seeder;

class CountryTimeZoneSeeder extends Seeder {
    public function run(): void {
        $countryBuilder = $this->db->table('glb_country');
        $tzBuilder = $this->db->table('glb_time_zone');
        $pivotBuilder = $this->db->table('glb_country_time_zone');
        $time = date('Y-m-d H:i:s');
        $inserted = 0;
        $updated = 0;

        $list = array_merge($this->getBaseData(), $this->getCustomData());
        foreach ($list as $countryCode => $zones) {
            $country = $countryBuilder
                ->select('id')
                ->where('code', $countryCode)
                ->limit(1)
                ->get()
                ->getRow();

            if (!$country) continue;

            foreach ($zones as $zone) {
                $tz = $tzBuilder
                    ->select('id')
                    ->where('code', $zone['zone'])
                    ->limit(1)
                    ->get()
                    ->getRow();

                if (!$tz) continue;

                $existing = $pivotBuilder
                    ->select('id')
                    ->where('country_id', $country->id)
                    ->where('time_zone_id', $tz->id)
                    ->limit(1)
                    ->get()
                    ->getRow();

                if ($existing) {
                    $pivotBuilder
                        ->where('id', $existing->id)
                        ->update([
                            'is_default' => $zone['default'] ? '1' : '0',
                            'updated_at' => $time,
                        ]);
                    $updated++;
                } else {
                    $pivotBuilder->insert([
                        'country_id'  => $country->id,
                        'time_zone_id' => $tz->id,
                        'is_default'  => $zone['default'] ? '1' : '0',
                        'created_at'  => $time,
                    ]);
                    $inserted++;
                }
            }
        }

        echo "  Zonas horarias por pais insertadas: {$inserted}, actualizadas: {$updated}" . PHP_EOL;
    }

